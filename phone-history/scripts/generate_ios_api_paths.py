#!/usr/bin/env python3
"""Generate Swift route constants from contracts/openapi.yaml."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
OPENAPI = ROOT / "contracts" / "openapi.yaml"
OUTPUT = ROOT / "ios" / "Core" / "GeneratedAPIPaths.swift"


def swift(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def has_method(operations: Any, method: str) -> bool:
    return isinstance(operations, dict) and method.lower() in {
        str(key).lower() for key in operations
    }


def pick(
    paths: dict[str, Any], method: str, include: tuple[str, ...], exclude: tuple[str, ...] = ()
) -> str:
    candidates: list[tuple[int, str]] = []
    for path, operations in paths.items():
        if not has_method(operations, method):
            continue
        lowered = path.lower()
        if any(term not in lowered for term in include) or any(term in lowered for term in exclude):
            continue
        candidates.append((len(path), path))
    return min(candidates, default=(0, ""))[1]


def main() -> int:
    document = yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))
    paths = document.get("paths") if isinstance(document, dict) else None
    if not isinstance(paths, dict):
        raise SystemExit("OpenAPI document has no paths object")

    ingest = pick(paths, "post", ("event",), ("encrypted", "delete", "review", "dismiss"))
    if not ingest:
        ingest = pick(paths, "post", ("ingest",), ("encrypted",))
    if not ingest:
        raise SystemExit("could not locate the batch ingest POST route")

    values = {
        "health": pick(paths, "get", ("health",)),
        "capabilities": pick(paths, "get", ("capab",)),
        "batchIngest": ingest,
        "encryptedBatchIngest": pick(paths, "post", ("encrypted",)),
        "timeline": pick(paths, "get", ("timeline",)),
        "episodes": pick(paths, "get", ("episode",)),
        "candidates": pick(paths, "get", ("candidate",)),
        "syncStatus": pick(paths, "get", ("sync", "status")),
        "maintenance": pick(paths, "post", ("maintenance",)),
        "eventDeleteTemplate": pick(paths, "delete", ("event",)),
        "candidateReviewTemplate": pick(paths, "post", ("candidate", "review")),
        "candidateDismissTemplate": pick(paths, "post", ("candidate", "dismiss")),
    }
    digest = hashlib.sha256(OPENAPI.read_bytes()).hexdigest()
    lines = "\n".join(f"    static let {key} = {swift(value)}" for key, value in values.items())
    source = f"""// Generated by scripts/generate_ios_api_paths.py. Do not hand-edit.
import Foundation

enum GeneratedPhoneHistoryAPIPaths {{
    static let openAPISHA256 = {swift(digest)}
{lines}
}}
"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(source, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

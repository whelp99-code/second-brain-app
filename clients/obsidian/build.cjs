'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root=__dirname;
const core=fs.readFileSync(path.join(root,'sync-core.cjs'),'utf8');
const main=fs.readFileSync(path.join(root,'main.src.cjs'),'utf8');
const output='// Generated by build.cjs; no runtime npm dependencies.\nconst syncCore=(()=>{const module={exports:{}};\n'+core+'\nreturn module.exports;})();\n'+main;
const destination=path.join(root,'dist');
fs.mkdirSync(destination,{recursive:true});
fs.writeFileSync(path.join(destination,'main.js'),output);
fs.copyFileSync(path.join(root,'manifest.json'),path.join(destination,'manifest.json'));
const hashes=Object.fromEntries(['main.js','manifest.json'].map(name=>[name,crypto.createHash('sha256').update(fs.readFileSync(path.join(destination,name))).digest('hex')]));
fs.writeFileSync(path.join(destination,'SHA256SUMS.json'),JSON.stringify(hashes,null,2)+'\n');
console.log(JSON.stringify({status:'built',files:Object.keys(hashes),sha256:hashes},null,2));
